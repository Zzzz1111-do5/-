  if (m.kind === 'asm') return m.src === 'eship' ? 'nsm' : e ? (m.src === 'b2' ? 'lrasm' : 'nsm') : 'yj83k';
  // 防空、空空
  if (m.src === 'aam') return e ? 'aim120' : m.lr ? 'pl17' : isFinite(m.x0) && Math.hypot(m.tx - m.x0, m.ty - m.y0) < 320 ? 'pl10' : 'pl15';
  if (m.src === 'manpads') return 'manpad';
  if (m.src === 'cv') return 'hhq10';
  if (m.src === 'eship') return 'sm6';
  if (m.src === 'dd' || m.src === 'esc') { const o = typeof v3VlsOrigin === 'function' ? v3VlsOrigin(m) : null; return o && o.cls === '054A' ? 'hhq16' : 'hhq9'; }
