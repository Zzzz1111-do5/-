// 这一速度下的性能（真实值）：ni 瞬时过载、ns 持续过载、wi / ws 瞬时 / 持续转弯角速度 rad/s、acc 平飞加速度 m/s²
function apPerf(key, V) {
  const A = AP[key];
  if (!A) return null;
  const W = A.m * AP_G, v = Math.max(V, 30), q = .5 * AP_RHO * v * v, qS = q * A.S, T = A.T * Math.pow(AP_RHO / 1.225, .7);
  const M = v / 320, sm = (a, b, x) => { const t = clamp((x - a) / (b - a), 0, 1); return t * t * (3 - 2 * t); }, CD0 = A.CD0 * (1 + 1.3 * sm(.85, 1.05, M) - .4 * sm(1.2, 1.8, M));   // 跨声速波阻
  const ni = Math.max(1, Math.min(A.nz, qS * A.CL / W)), D0 = qS * CD0;
  const ns = Math.max(1, Math.min(ni, Math.sqrt(Math.max(0, (T - D0) * qS / (A.K * W * W)))));
  return { ni, ns, wi: AP_G * Math.sqrt(ni * ni - 1) / v * (A.tvc || 1), ws: AP_G * Math.sqrt(ns * ns - 1) / v, acc: (T - D0 - A.K * W * W / qS) / A.m, T, D0, qS, W, vs: Math.sqrt(2 * W / (AP_RHO * A.S * A.CL)) };
}
// 推演里的空战最大转弯角速度（rad/s，已乘 AP_K）：瞬时转弯——速度掉了，能拉的过载跟着少
function apTurn(key, V, def) { const P = apPerf(key, V); return P ? P.wi * AP_K : def; }
// 速度变化（推演里的，已乘 AP_K）：想要的速度 v、现在的转弯角速度 hr（推演里的 rad/s）——
//   加速靠剩余推力（转弯拉的过载越大阻力越大、剩余推力越少，转得比持续转弯还急时是负的：边转边掉速）；减速：收油门 + 减速板；不掉到失速速度以下
function apDv(key, V, v, hr, dt) {
  const A = AP[key], P = A && apPerf(key, V);
  if (!P) return null;
  const n = Math.min(P.ni, Math.sqrt(1 + (V * Math.abs(hr || 0) / AP_K / AP_G) ** 2)), D = P.D0 + A.K * (n * P.W) ** 2 / P.qS;
  const up = (P.T - D) / A.m * AP_K, dn = -(D + .5 * P.D0 + (A.sb || .05) * P.W) / A.m * AP_K;
  const r = v > V ? V + (up > 0 ? Math.min(v - V, up * dt) : up * dt) : V + Math.max(v - V, Math.min(up, dn) * dt);
  return V > P.vs * 1.1 ? Math.max(r, P.vs * 1.1) : r;
}
// 信息卡用：这一型的机动性（真实值，5000 米、250 米 / 秒）
function apCard(key) {
  const A = AP[key], P = A && apPerf(key, 250);
  if (!P) return null;
  const d = r => Math.round(r * 180 / Math.PI);
  return `推重比 ${(A.T / (A.m * AP_G)).toFixed(2)} · 翼载 ${Math.round(A.m / A.S)} kg/m² · 过载限制 ${A.nz} g · 瞬时转弯 ${d(P.wi)}°/s · 持续转弯 ${d(P.ws)}°/s（${P.ns.toFixed(1)} g）· 平飞加速 ${P.acc.toFixed(1)} m/s²（5000 米、250 米 / 秒）`;
}
